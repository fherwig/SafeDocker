# Read a password from the terminal, without echo, into PASSWORD
read_password() {
    printf "%s" "$1">&2
    if [ -t 0 ]; then stty -echo; fi
    IFS= read -r PASSWORD
    READ_STATUS=$?
    if [ -t 0 ]; then stty echo; fi
    echo>&2
    if [ $READ_STATUS != 0 ]
    then
        echo "Error: no password read.">&2
    fi
    return $READ_STATUS
}

# Run openssl enc with the password in PASSWORD. openssl reads it from a
# pipe, so it never shows up on a command line.
openssl_pw() {
    printf '%s\n' "$PASSWORD" | $openssl_bin enc $CIPHER_OPTS -pass stdin "$@"
}

# Encryption mode
encryption() {
    echo "Encrypting $1..."
    rm -f "$1.crypt_new"
    TRIES=0
    while : ; do
        TRIES=`expr $TRIES + 1`
        if [ $TRIES -gt 3 ]
        then
            echo "Error: passwords did not match. $1 not encrypted.">&2
            return 1
        fi
        read_password "Password: " || return 1
        PASSWORD1=$PASSWORD
        read_password "Verify password: " || return 1
        if [ -z "$PASSWORD" ]
        then
            echo "Empty password. Try again.">&2
        elif [ "$PASSWORD" != "$PASSWORD1" ]
        then
            echo "Passwords do not match. Try again.">&2
        else
            break
        fi
    done
    PASSWORD1=

#   Warn if this password does not open the existing encrypted file
    if [ -f "$1.crypt" ] && ! openssl_pw -d -in "$1.crypt" -out /dev/null 2>/dev/null
    then
        echo "WARNING: this password does not open the existing $1.crypt.">&2
        printf "Encrypt %s with this new password anyway? [y/N] " "$1">&2
        read ANSWER
        case $ANSWER in
            y|Y|yes|Yes|YES)
                ;;
            *)  PASSWORD=
                echo "$1 not encrypted.">&2
                return 1
                ;;
        esac
    fi

#   Encrypt to a new file and check that it decrypts back to the plaintext
    if ! openssl_pw -e -in "$1" -out "$1.crypt_new" || \
       ! openssl_pw -d -in "$1.crypt_new" | cmp -s - "$1"
    then
        PASSWORD=
        rm -f "$1.crypt_new"
        echo "Error: encryption of $1 failed. Nothing changed.">&2
        return 1
    fi
    PASSWORD=

    if [ -f "$1.crypt" ] && ! cp -f "$1.crypt" "$1.crypt.bak"
    then
        rm -f "$1.crypt_new"
        echo "Error: could not save $1.crypt.bak. Nothing changed.">&2
        return 1
    fi
    if ! mv -f "$1.crypt_new" "$1.crypt"
    then
        echo "Error: could not move $1.crypt_new to $1.crypt.">&2
        return 1
    fi
    if [ $DELT = TRUE ]
    then
        rm -f "$1"
    fi
}

# Decryption mode
decryption() {
#   Check to see if the file is really encrypted.
    INPUT="a`dd if="$1" bs=8 count=1 2>/dev/null`"
    if [ "$INPUT" != "aSalted__" ]
    then
        echo "Error: $1 cannot be decrypted.">&2
        return 1
    fi
    OUTFILE="${1%.crypt}"
    if [ -z "$OUTFILE" -o "$OUTFILE" = "$1" ]
    then
        echo "Error: $1 does not end in .crypt, so there is no name to decrypt it to.">&2
        echo "       Copy it to a name that ends in .crypt first, e.g. cp $1 old.txt.crypt">&2
        return 1
    fi
    if [ -e "$OUTFILE" ]
    then
        echo "Error: $OUTFILE exists already. Not overwriting it.">&2
        return 1
    fi
    echo "Decrypting $1..."
    read_password "Password: " || return 1
    if ! openssl_pw -d -in "$1" -out "$OUTFILE"
    then
        PASSWORD=
        rm -f "$OUTFILE"
        echo "Error: decryption of $1 failed (wrong password?). Nothing changed.">&2
        return 1
    fi
    PASSWORD=
    if [ $DELT = TRUE ]
    then
        rm -f "$1"
    fi
}

# Automatic mode
autodetect() {
# Check the file header to see if the file is encrypted
    INPUT="a`dd if="$1" bs=8 count=1 2>/dev/null`"
    if [ "$INPUT" = "aSalted__" ]
    then
        decryption "$1"
    else
        encryption "$1"
    fi
}



#################
## Begin
#################

ENCRYPT=FALSE
DECRYPT=FALSE
DELT=FALSE
STATUS=0
CIPHER_OPTS="-aes-256-cbc -md sha512 -pbkdf2 -iter 100000 -salt"
openssl_bin="/usr/bin/openssl"

# New files, the plaintext included, are readable by the owner only
umask 077
# Give the terminal its echo back if we are interrupted at a password prompt
trap 'if [ -t 0 ]; then stty echo; fi' EXIT
trap 'exit 1' INT TERM HUP

# Parsing command line
CMDNAME=`basename $0`
USAGE="Usage: $CMDNAME [-d -e -r -v] file(s)\n          \
-d        Force decryption\n          \
-e        Force encryption\n          \
-r        Delete original file\n          \
-v        Show version information\n"
if [ "$#" -lt 1 ]
then
    printf "$USAGE">&2
    exit 1
fi

# Parse options.
while getopts edrv OPT
do
    case $OPT in
        e)      ENCRYPT=TRUE        # forces encryption
                ;;
        d)      DECRYPT=TRUE        # forces decryption
                ;;
        r)      DELT=TRUE           # delete original file
                ;;
        v)      echo "Version 1.5, released 2026-10-24." # print version information
                ;;
        \?)     printf "$USAGE">&2  # invalid options
                exit 1
                ;;
    esac
done

shift `expr $OPTIND - 1`

# Check if force encrypt and decrypt are specified at the same time
if [ $ENCRYPT = TRUE -a $DECRYPT = TRUE ]
then
    echo "Error: -e and -d cannot be used simultaneously.">&2
    exit 1
fi


# Main
for FILE in "$@"
do
#   Check input file sanity
    if [ -d "$FILE" ]
    then
        echo "Error: $FILE is a directory. Unable to encrypt/decrypt a directory.">&2
        STATUS=1
        continue
    fi

    if [ ! -r "$FILE" ]
    then
        echo "Error: $FILE is not readable. Unable to encrypt/decrypt.">&2
        STATUS=1
        continue
    fi

#   Process files
    if [ $ENCRYPT != TRUE -a $DECRYPT != TRUE ]
    then
        autodetect "$FILE" || STATUS=1
    else
        if [ $DECRYPT = TRUE ]
        then
            decryption "$FILE" || STATUS=1
        else
            encryption "$FILE" || STATUS=1
        fi
    fi
done

exit $STATUS
